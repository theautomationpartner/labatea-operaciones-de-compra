/**
 * Grabación del video "Cómo crear una orden de compra".
 * Uso: node scripts/grabar-crear-oc.mjs        (RAPIDO=1 para probar los selectores sin grabar)
 *
 * Cada acción espera a la palabra de la voz que la nombra (`en('palabra')`). Los zooms quedan
 * marcados con la caja del elemento en px de la página; el montaje los aplica.
 */
import { iniciarGrabacion } from '../lib/grabador.mjs'

const PRODUCTO = 'BOOSTER ESSENTIAL LACTOREEMPLAZANTE x 20 Kgs.'

const g = await iniciarGrabacion({
  nombre: 'crear-oc',
  listo: (p) => p.getByText('The Automation Partner', { exact: true }).first().waitFor(),
})
const { page, parte, en, clic, tipear, zoom, unir, carga, espera } = g
const btn = (texto) => page.locator(`button:visible:text-is("${texto}")`)
const pasos = page.locator('.paso-header-steps:not([aria-hidden="true"])')

try {
  /* ===== Parte 1 — Elegir la operación ===== */
  await parte('p1', async () => {
    const selOperacion = page.locator('button.selbox:visible').nth(0)
    const selComprador = page.locator('button.selbox:visible').nth(1)
    const lblOperacion = page.locator('.topsel-lbl:visible').nth(0)
    const lblComprador = page.locator('.topsel-lbl:visible').nth(1)

    await en('abrimos', 0.4)
    await clic(selOperacion)
    await zoom(unir(lblOperacion, page.getByText('ACTUALIZAR PRECIOS', { exact: true })), { hasta: 'Crear' })
    await en('Crear')
    await clic(page.getByText('CREAR ORDEN DE COMPRA', { exact: true }).last())
    await en('Esta')
    await zoom(unir(lblOperacion, selOperacion), { hasta: 'campo' })
    await en('campo')
    await zoom(unir(lblComprador, selComprador), { hasta: 'Confirmamos' })
    await en('Confirmamos', 0.3)
    await clic(btn('Confirmar'))
    await carga(() => pasos.waitFor({ state: 'visible' }))
    await en('tres', 0.2)
    await zoom(pasos, { hasta: 99 })
  })

  /* ===== Parte 2 — Etapa 1: seleccionar proveedor ===== */
  await parte('p2', async () => {
    const buscador = page.getByPlaceholder('Buscar proveedor por código, nombre o CUIT...')
    await en('Escribimos', 0.2)
    await zoom(unir(buscador, btn('Buscar')), { hasta: 'Como' })
    await clic(buscador)
    await tipear('Provimi')
    await en('clic', 0.2)
    await clic(btn('Buscar'))
    await carga(() => page.locator('.client-name').getByText('PROVIMI').waitFor())
    await en('Como', 0.1)
    await zoom(page.locator('.client-header'), { hasta: 'Vemos' })
    await en('codigo', 0.3)
    await zoom(page.locator('.client-id'), { hasta: 'estado' })
    await en('estado', 0.1)
    await zoom(page.locator('.status-indicator').nth(0), { hasta: 'situacion' })
    await en('situacion', 0.1)
    await zoom(page.locator('.status-indicator').nth(1), { hasta: 'direccion' })
    await en('direccion', 0.3)
    await zoom(page.locator('.client-address'), { hasta: 'CUIT' })
    await en('CUIT', 0.2)
    await zoom(page.locator('.badges .badge-gray').nth(0), { hasta: 'tipo' })
    await en('tipo', 0.1)
    await zoom(page.locator('.badges .badge-gray').nth(1), { hasta: 'condicion' })
    await en('condicion', 0.1)
    await zoom(page.locator('.badges .badge-green'), { hasta: 'condicion' })
    await en('condicion', 0.1)
    await zoom(page.locator('.badges .badge--cond').nth(0), { hasta: 'dias' })
    await en('dias', 0.3)
    await zoom(page.locator('.badges .badge--cond').nth(1), { hasta: 'Mas' })
    await en('cuenta', 0.4)
    await zoom(page.locator('.kpi-grid--5'), { hasta: 'credito' })
    await en('credito', 0.2)
    await zoom(unir(page.locator('.credito-fila-inferior'), page.locator('.credito-nota-off')), { hasta: 'Continuamos' })
    await en('Continuamos')
    await zoom(btn('Continuar a Seleccionar Productos'), { hasta: 99, apartar: false })
    await clic(btn('Continuar a Seleccionar Productos'))
    await carga(() => page.getByPlaceholder('Buscar por nombre, código o filtros aplicados').waitFor())
  })

  /* ===== Parte 3 — Etapa 2: búsqueda y ficha del producto ===== */
  await parte('p3', async () => {
    const buscador = page.getByPlaceholder('Buscar por nombre, código o filtros aplicados')
    const item = page.locator('.ritem', { hasText: PRODUCTO })
    await en('La', 0)
    await zoom(pasos, { hasta: 'En' })
    await en('solo', 0.3)
    await zoom(page.locator('.step-desc-main:visible'), { hasta: 'Buscamos' })
    await en('Buscamos', 0.2)
    await clic(buscador)
    await tipear('Booster')
    await clic(btn('Buscar'))
    await carga(() => item.waitFor())
    await en('Consignado', 0.4)
    await zoom(unir(item.locator('.ritem-name'), item.getByText('Consignado', { exact: true })), { hasta: 'y' })
    await en('codigo', 0.3)
    await zoom(item.locator('.ritem-code'), { hasta: 'Hacemos' })
    await en('Booster', 0.3)
    await clic(item.locator('.ritem-name'))
    await carga(() => page.locator('.product-name', { hasText: PRODUCTO }).waitFor())
    await en('Esto', 0.1)
    await zoom(page.locator('.cl-info'), { hasta: 'nombre' })
    await en('nombre', 0.2)
    await zoom(page.locator('.product-name'), { hasta: 'costo' })
    await en('costo', 0.2)
    await zoom(page.locator('.cl-kpi').nth(0), { hasta: 'tipo' })
    await en('tipo', 0.2)
    await zoom(page.locator('.cl-kpi').nth(1), { hasta: 'cantidad' })
    await en('cantidad', 0.2)
    await zoom(page.locator('.cl-kpi').nth(2), { hasta: 99 })
  })

  /* ===== Parte 4 — Etapa 2: cantidades, costo y stock ===== */
  await parte('p4', async () => {
    const cxe = page.getByLabel('Cant x Envase para esta orden')
    const envases = page.getByLabel('Cantidad de envases a pedir')
    await en('Cambiamos', 0.2)
    await clic(cxe)
    await page.keyboard.press('Control+A')
    await tipear('40')
    await page.keyboard.press('Tab')
    await zoom(page.locator('.cl-kpi').nth(2), { hasta: 'El' })
    await en('aviso', 0.3)
    await zoom(page.locator('.cl-aviso-envase'), { hasta: 'La' })
    await en('La', 0)
    await zoom(page.locator('.cl-kpi').nth(2), { hasta: 'color' })
    await en('color', 0.2)
    await zoom(page.locator('.cl-aviso-envase'), { hasta: 'Ajustamos' })
    await en('Ajustamos', 0.2)
    await zoom(page.locator('.qty-input-group').nth(0), { hasta: 'La' })
    await clic(page.getByLabel('Sumar un envase'))
    await espera(350)
    await clic(page.getByLabel('Sumar un envase'))
    await espera(350)
    await clic(page.getByLabel('Sumar un envase'))
    await en('menos', 0.1)
    await clic(page.getByLabel('Restar un envase'))
    await en('escribimos', 0.2)
    await clic(envases)
    await page.keyboard.press('Control+A')
    await page.keyboard.press('Backspace')
    await en('seis', 0.3)
    await tipear('6')
    await en('La', 0.1)
    await zoom(page.locator('.cl-oper .control-item').nth(1), { hasta: 'En' })
    await en('detalle', 0.3)
    await zoom(page.locator('.cl-bottom .lindet-rows'), { hasta: 'A' })
    await en('stock', 0.3)
    await zoom(page.locator('.cl-stock'), { hasta: 'Hacemos' })
    await en('Hacemos', 0)
    await zoom(btn('Agregar'), { hasta: 99, apartar: false })
    await en('Agregar', 0.3)
    await clic(btn('Agregar'))
  })

  /* ===== Parte 5 — Etapa 2: tabla de la orden y totales ===== */
  await parte('p5', async () => {
    const fila = page.locator('tr', { hasText: PRODUCTO }).first()
    for (let i = 0; i < 4; i++) {
      await page.mouse.wheel(0, 90)
      await espera(90)
    }
    await espera(300)
    await en('El', 0)
    await zoom(unir(page.locator('.tablec thead'), fila), { hasta: 'Si' })
    await en('sumamos', 0.1)
    await clic(page.getByLabel(`Sumar un envase de ${PRODUCTO}`))
    await zoom(unir(fila.getByLabel(`Envases a comprar de ${PRODUCTO}`), fila.locator('td', { hasText: /^\s*\$/ }).last()), { hasta: 'Al' })
    await en('desplegar', 0.2)
    await clic(fila.locator('.chev'))
    await espera(400)
    for (let i = 0; i < 4; i++) {
      await page.mouse.wheel(0, 80)
      await espera(90)
    }
    await espera(300)
    await zoom(page.locator('.lindet:visible').first(), { hasta: 'Mas' })
    await en('Mas', 0.2)
    for (let i = 0; i < 10; i++) {
      await page.mouse.wheel(0, 90)
      await espera(90)
    }
    await espera(300)
    await en('totales', 0.4)
    await zoom(page.locator('.subtotal-lines'), { hasta: 'Al' })
    await en('lado', 0.3)
    await zoom(page.locator('.indicadores-layout'), { hasta: 'Continuamos' })
    await en('Continuamos', 0.1)
    await zoom(btn('Continuar a Emitir y Enviar'), { hasta: 99, apartar: false })
    await clic(btn('Continuar a Emitir y Enviar'))
    await carga(async () => {
      await page.locator('.resumen-emision').waitFor()
      await page.locator('.resumen-emision .rrow', { hasText: /N° de orden.*\d/ }).waitFor()
      await page.locator('.contactos-cargando').waitFor({ state: 'detached' }).catch(() => {})
    })
  })

  /* ===== Parte 6 — Etapa 3: emitir y enviar ===== */
  await parte('p6', async () => {
    await en('La', 0)
    await zoom(page.locator('.resumen-emision .rgroup').first(), { hasta: 'Hacemos' })
    await en('Hacemos', 0.1)
    await clic(btn('EMITIR ORDEN DE COMPRA'))
    await carga(() => page.getByText('Orden de compra emitida').waitFor({ timeout: 180000 }))
    await zoom(unir(page.locator('.btn-generar'), page.locator('.pres-pdf-btn')), { hasta: 'Con' })
    await en('Ver', 0.3)
    const [pestana] = await Promise.all([
      page.context().waitForEvent('page'),
      clic(page.locator('.pres-pdf-btn')),
    ])
    await carga(async () => {
      await pestana.waitForLoadState('load')
      await pestana.waitForTimeout(1800)
    })
    await g.filmarPestana(pestana)
    await zoom({ x: 560, y: 70, width: 780, height: 430 }, { hasta: 'Volvemos', apartar: false })
    await en('Volvemos', 0.1)
    await pestana.close()
    await g.volverA(page)
    await en('tarjeta', 0.2)
    const card = page.locator('.comp-card').first()
    await zoom(card, { hasta: 'El' })
    await en('cerrar', 0.2)
    await clic(page.locator('button.comp-toggle'))
    await en('abrir', 0.3)
    await clic(page.locator('button.comp-toggle'))
    await en('medio', 0.2)
    await zoom(page.locator('.envio-medio-linea'), { hasta: 'En' })
    await en('Seleccionar', 0.3)
    const picker = page.getByPlaceholder('Buscar y seleccionar contactos...')
    await zoom(picker, { hasta: 'listan' })
    await en('listan', 0.2)
    await clic(picker)
    await zoom(unir(picker, page.locator('.cddlist')), { hasta: 'Elegimos' })
    await en('Elegimos', 0.1)
    await clic(page.locator('.cddlist li', { hasText: 'Luciano 1' }))
    const contacto = page.locator('.citem', { hasText: 'Luciano 1' })
    await zoom(contacto, { hasta: 'hacemos' })
    await en('hacemos', 0.1)
    await zoom(contacto.locator('.citem-editar'), { hasta: 'Aca', apartar: false })
    await en('Editar', 0.2)
    await clic(contacto.locator('.citem-editar'))
    await en('Aca', 0.2)
    const acepta = page.locator('.editar-contacto-check')
    await zoom(acepta, { hasta: 'El' })
    await en('marcamos', 0.3)
    await clic(acepta.locator('input'))
    await en('email', 0.3)
    await zoom(unir(page.locator('label[for="ec-email"]'), page.locator('#ec-email')), { hasta: 'Al' })
    await en('confirmar', 0.3)
    const confirmar = page.locator('button:visible:text-is("Confirmar")').last()
    await zoom(confirmar, { hasta: 'los', apartar: false })
    await clic(confirmar)
    await page.locator('.citem .cbadge.ok').waitFor()
    await en('Ahora', 0.2)
    await zoom(unir(contacto.locator('.citem-name'), contacto.locator('.cbadge')), { hasta: 99 })
  })
} catch (e) {
  console.error('ERROR', e)
  await page.screenshot({ path: 'grabaciones/crear-oc/error.png' }).catch(() => {})
}
await g.terminar()
